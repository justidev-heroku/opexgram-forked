#pragma once

#include <string>
#include <string_view>

namespace MTP::details {

// StaticGram: signed server-address record, same format and check as the
// Android client (tgnet ConnectionsManager.cpp verifyShuzaGramAttestation).
//
// TXT _cfg.staticgram.top = "v1:<ip>:<port>:<base64 signature>", where the
// signature is RSASSA-PKCS1-v1_5 / SHA-256 over the ASCII bytes "<ip>:<port>"
// made with the server identity key (the MTProto RSA key, fp
// 0x857119f27ae9c9fc). The port is pinned by the client: a record naming any
// other port is rejected. There is no expiry field; a record stays valid until
// the key changes. Generated by /root/staticgram-assets/sg-cfg-txt.py.
//
// Kept free of Qt / tdesktop headers so it can be unit-tested with plain
// OpenSSL.

// The "data" field of a DoH JSON TXT answer: Cloudflare returns the quoted
// character-strings ("\"part1\" \"part2\""), Google the joined bare text.
// Returns the joined text without quotes (same as Android unquoteTxt()).
[[nodiscard]] std::string UnquoteDnsTxt(std::string_view value);

// Returns the <ip> part of a correctly signed record, or an empty string if
// the record is malformed, names another port or the signature does not
// verify against publicKeyPem ("-----BEGIN RSA PUBLIC KEY-----", PKCS#1).
// The caller still has to check that the ip is a usable public IPv4.
[[nodiscard]] std::string VerifySignedServerTxt(
	std::string_view txt,
	std::string_view publicKeyPem,
	int pinnedPort);

} // namespace MTP::details
