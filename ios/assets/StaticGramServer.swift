// StaticGram: the MTProto server address is not baked in for good.
//
// - Every datacenter is seeded with the reserve IPs below; MTContext always
//   merges the seed set into the candidates it tries, so they stay usable
//   even when a saved (older) dc_options address is dead.
// - The signed TXT _cfg.staticgram.top is fetched at startup and again when
//   MTContext asks for backup addresses after connection failures
//   (debounced), over DNS-over-HTTPS only (Cloudflare, Google). System DNS
//   and unsigned A records of dc.staticgram.top are not used: a spoofed
//   answer must not move the client to a foreign IP.
// - Record format (same as Android tgnet verifyShuzaGramAttestation and
//   desktop): "v1:<ip>:<port>:<base64 signature>", the signature is
//   RSASSA-PKCS1-v1_5 / SHA-256 over the bytes "<ip>:<port>" made with the
//   server identity key (the MTProto RSA key, fp 0x857119f27ae9c9fc;
//   generated by sg-cfg-txt.py). The port must equal sgServerPort. No expiry.
// - Only a public IPv4 outside Cloudflare ranges is accepted (a proxied DNS
//   record points at Cloudflare, MTProto on our port does not pass there).
// - A verified address replaces the saved address set of every datacenter
//   and the addresses advertised by help.getConfig. If nothing verifies, the
//   current addresses (always including the reserve IPs) stay.

let sgServerHost = "_cfg.staticgram.top"
let sgServerPort: UInt16 = 2398
